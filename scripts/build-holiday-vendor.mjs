// Run with a temporary npm prefix containing date-holidays@3.36.1 and esbuild@0.25.10.
// npm install --prefix <temp> --ignore-scripts --no-audit --no-fund date-holidays@3.36.1 esbuild@0.25.10
// node scripts/build-holiday-vendor.mjs <temp>
import { readFile, writeFile, mkdir, readdir } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { pathToFileURL } from "node:url";
import { normalizeHolidayName, holidayAliases } from "../plugins/until/holiday-names.mjs";
import { supplementalHolidays } from "../plugins/until/holiday-supplement.mjs";

const prefix = resolve(process.argv[2] || "");
const modules = resolve(prefix, "node_modules");
const pkg = JSON.parse(await readFile(resolve(modules, "date-holidays/package.json")));
if (pkg.version !== "3.36.1") throw new Error("Expected date-holidays 3.36.1");
const { default: Holidays } = await import(pathToFileURL(resolve(modules, "date-holidays/src/index.js")));
const { build } = await import(pathToFileURL(resolve(modules, "esbuild/lib/main.js")));
const root = new URL("../plugins/until/", import.meta.url);
const output = new URL("vendor/date-holidays/", root);
await mkdir(output, { recursive: true });
const result = await build({
  entryPoints: [resolve(modules, "date-holidays/src/index.js")],
  outfile: new URL("index.mjs", output).pathname,
  bundle: true, platform: "node", format: "esm", target: "es2022",
  minify: true, legalComments: "eof", metafile: true,
});
const explorer = new Holidays();
const calendars = {};
const names = {};
function addName(name, id, english) {
  const key = normalizeHolidayName(name);
  if (key.length < 3 || key.length > 120) return;
  const entries = names[key] ||= [];
  if (!entries.some(([c, n]) => c === id && n === english)) entries.push([id, english]);
}
function addCalendar(id, label) {
  calendars[id] = label;
  const h = new Holidays(id, { languages: "en" });
  for (const rule of h.getRules()) {
    if (!rule.name) continue;
    const english = rule.name.en || Object.values(rule.name)[0];
    for (const name of Object.values(rule.name)) addName(name, id, english);
    // Parenthetical alternative names, never arbitrary substrings of a holiday.
    const parenthesis = english.match(/^(.+?)\s+\(([^)]+)\)$/);
    if (parenthesis && !/day \d|intermediate|substitute|observed/i.test(parenthesis[2])) {
      addName(parenthesis[1], id, english);
      addName(parenthesis[2], id, english);
    }
  }
}
for (const [country, name] of Object.entries(explorer.getCountries("en"))) {
  addCalendar(country, name);
  for (const [state, stateName] of Object.entries(explorer.getStates(country, "en") || {})) {
    addCalendar(`${country}.${state}`, `${name} / ${stateName}`);
    for (const [region, regionName] of Object.entries(explorer.getRegions(country, state, "en") || {})) {
      addCalendar(`${country}.${state}.${region}`, `${name} / ${stateName} / ${regionName}`);
    }
  }
}
for (const entry of supplementalHolidays) addName(entry.name, entry.calendar, entry.name);
// Alias equivalence is shared across regional variants (e.g. Christmas Day).
for (const group of holidayAliases) {
  const entries = group.flatMap(name => names[normalizeHolidayName(name)] || []);
  for (const name of group) for (const [id, english] of entries) addName(name, id, english);
}
const sortedNames = Object.fromEntries(Object.entries(names).sort(([a], [b]) => a.localeCompare(b)));
// Intern repeated English names and calendar IDs; inherited regional rules
// otherwise repeat several megabytes of identical names in the alias index.
const calendarIds = Object.keys(calendars);
const records = [];
const recordIds = new Map();
const compactNames = {};
for (const [alias, entries] of Object.entries(sortedNames)) {
  const ids = new Set();
  for (const [calendar, english] of entries) {
    if (!recordIds.has(english)) { recordIds.set(english, records.length); records.push([english, []]); }
    const id = recordIds.get(english);
    const index = calendarIds.indexOf(calendar);
    if (!records[id][1].includes(index)) records[id][1].push(index);
    ids.add(id);
  }
  compactNames[alias] = [...ids];
}
await writeFile(new URL("catalog.mjs", output),
  `// Generated by scripts/build-holiday-vendor.mjs; data adapted under CC BY-SA 3.0. See LICENSES.txt.\nexport const calendars=${JSON.stringify(calendars)};\nexport const names=${JSON.stringify(compactNames)};\nexport const records=${JSON.stringify(records)};\n`);
// Tiny, standalone exact-name guards: Store plugins cannot import sibling folders.
const guard = `// Generated holiday names; CC BY-SA 3.0. See holiday-names.LICENSE.txt.\nconst names=new Set(${JSON.stringify(Object.keys(sortedNames))});\nexport function isHolidayName(value){return names.has(${normalizeHolidayName.toString()}(value));}\n`;
const licenses = [];
const usedPackages = new Set(Object.keys(result.metafile.inputs).map(path => {
  const after = path.split("node_modules/").pop();
  return after?.split("/")[0];
}));
for (const name of [...usedPackages].sort()) {
  const dir = resolve(modules, name);
  const license = (await readdir(dir)).find(file => /^licen[sc]e(?:\.md|\.txt)?$/i.test(file));
  if (!license) throw new Error(`Missing license: ${name}`);
  const info = JSON.parse(await readFile(resolve(dir, "package.json")));
  licenses.push(`${name}@${info.version}\n${await readFile(resolve(dir, license), "utf8")}`);
}
await writeFile(new URL("LICENSES.txt", output), licenses.join("\n\n----------\n\n"));
for (const plugin of ["time", "osm-slot"]) {
  const dest = new URL(`../${plugin}/holiday-names.mjs`, root);
  await mkdir(dirname(dest.pathname), { recursive: true });
  await writeFile(dest, guard);
  await writeFile(new URL(`../${plugin}/holiday-names.LICENSE.txt`, root), await readFile(resolve(modules, "date-holidays/LICENSE")));
}
console.log(`${Object.keys(explorer.getCountries()).length} countries; ${Object.keys(calendars).length} calendars; ${Object.keys(names).length} names/aliases`);
